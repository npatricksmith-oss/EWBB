#!/usr/bin/env python3
"""Regenerates tracking/TEAMS_MANIFEST.md from the roster specs and build reports."""
import json
import os

PROJECT_DIR = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
TASKS = os.path.join(PROJECT_DIR, 'tracking', 'tasks', 'teams')
RESULTS = os.path.join(PROJECT_DIR, 'tracking', 'results')



def split_label(player):
    src = player['source']
    cov = src.get('splitCoverage')
    return src['splits'] + (f' ({cov:.0%} of season)' if cov is not None else '')


order = json.load(open(os.path.join(TASKS, 'order.json')))
lines = [
    '# 1987 Earl Weaver Baseball — Shipped Teams & Roster Manifest',
    '',
    'Generated by `bin/write_manifest.py` from `tracking/tasks/teams/*.json` and `tracking/results/build_*.json`.',
    '',
    'The base game shipped eight era all-star teams; the IBM version also had the 1982 Angels and Braves.',
    'No public source lists the original era rosters, so those are reconstructions (see `BLOCKERS_AND_QUESTIONS.md`).',
    'All season totals and L/R splits are real baseball-reference data; the 1–10 ratings are derived.',
    'The hand-built Orioles and Red Sox in `src/data/rosters.js` predate this pipeline and are not listed here.',
    '',
    '**Split sources:** *platoon* = true vs-LHP/RHP splits; *starter-hand* = split by the opposing starter\'s hand;',
    '*estimated* = no split data for that season, so typical platoon gaps were applied to the season totals.',
    'A percentage means play-by-play survives for only that share of the season; the observed L/R',
    'distribution is scaled up so L + R equals the season total.',
    '',
    '| Team Key | Team | Batters | Pitchers | Split sources | Status |',
    '| :--- | :--- | :---: | :---: | :--- | :--- |',
]
rosters = []
for tid in order:
    spec_path = os.path.join(TASKS, f'{tid}.json')
    build_path = os.path.join(RESULTS, f'build_{tid}.json')
    if not os.path.exists(spec_path):
        lines.append(f'| `{tid}` | — | — | — | — | Pending |')
        continue
    spec = json.load(open(spec_path))
    title = f"{spec['city']} {spec['name']}"
    if not os.path.exists(build_path):
        lines.append(f'| `{tid}` | {title} | — | — | — | Roster picked, not built |')
        continue
    build = json.load(open(build_path))
    players = build['batters'] + build['pitchers']
    counts = {}
    for p in players:
        counts[p['source']['splits']] = counts.get(p['source']['splits'], 0) + 1
    split_text = ', '.join(f'{n} {k}' for k, n in sorted(counts.items(), key=lambda kv: -kv[1]))
    status = '✅ Ingested' + (f" ({len(build['warnings'])} warnings)" if build['warnings'] else '')
    lines.append(f"| `{tid}` | {title} | {len(build['batters'])} | {len(build['pitchers'])} | {split_text} | {status} |")
    rosters.append(f'\n### {title} (`{tid}`)\n')
    rosters.append('| Player | Season | Pos/Role | Line | Splits |')
    rosters.append('| :--- | :---: | :---: | :--- | :--- |')
    for b in build['batters']:
        t = b['splits']['T']
        slot = b['pos'] + ('' if b['isStarter'] else ' (bench)')
        rosters.append(f"| {b['name']} | {b['source']['season']} | {slot} | "
                       f"{t['BA']:.3f}/{t['OBA']:.3f}/{t['SA']:.3f}, {t['HR']} HR | {split_label(b)} |")
    for p in build['pitchers']:
        t = p['splits']['T']
        rosters.append(f"| {p['name']} | {p['source']['season']} | {p['role']} | "
                       f"{t['W']}-{t['L']}, {t['ERA']:.2f} ERA, {t['IP']} IP, {t['SV']} SV | {split_label(p)} |")
lines += ['', '## Rosters'] + rosters + ['']

with open(os.path.join(PROJECT_DIR, 'tracking', 'TEAMS_MANIFEST.md'), 'w') as f:
    f.write('\n'.join(lines))
print('wrote tracking/TEAMS_MANIFEST.md')
